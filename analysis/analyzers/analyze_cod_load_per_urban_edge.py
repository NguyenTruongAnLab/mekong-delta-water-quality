#!/usr/bin/env python3
"""analyze_cod_load_per_urban_edge.py

Reviewer4 point #5: provide a simple mechanistic proxy linking configuration
(edge density) to loads.

Using the station-year load/intensity table generated by
analyze_load_intensity_and_mass_balance.py, we compute a proxy "COD load per
km of urban edge" as:

  COD_kg_day / Urban_edge_km

where:
  COD_kg_day = COD_Load_tons_day * 1000
  Urban_edge_km = (Residential_Urban_config_ED [m/ha] * Buffer_area_ha) / 1000

We summarize this proxy across Urban Patch Density (PD) quartiles.

Outputs (analysis/analysis_outputs):
- cod_load_per_urban_edge_km_by_pd_latest.csv

Notes
-----
- ED units are assumed to be meters per hectare (typical landscape-metric ED).
- This is a heuristic diagnostic, not a calibrated per-outfall estimate.
"""

from __future__ import annotations

import os

import numpy as np
import pandas as pd


SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
OUTPUT_DIR = os.path.join(SCRIPT_DIR, "analysis_outputs")
os.makedirs(OUTPUT_DIR, exist_ok=True)

IN_FILE = os.path.join(OUTPUT_DIR, "cod_load_intensity_station_year_latest.csv")


def main() -> None:
    if not os.path.exists(IN_FILE):
        raise FileNotFoundError(IN_FILE)

    df = pd.read_csv(IN_FILE)

    needed = [
        "COD_Load_tons_day",
        "Residential_Urban_config_ED",
        "Buffer_area_ha",
        "Urban_PD_quantile",
    ]
    missing = [c for c in needed if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns: {missing}")

    d = df[needed].copy()
    for c in ["COD_Load_tons_day", "Residential_Urban_config_ED", "Buffer_area_ha"]:
        d[c] = pd.to_numeric(d[c], errors="coerce")

    d = d.dropna().copy()

    # Compute edge length (km) and load per edge (kg/km/day)
    d["COD_kg_day"] = d["COD_Load_tons_day"] * 1000.0
    d["Urban_edge_km"] = (d["Residential_Urban_config_ED"] * d["Buffer_area_ha"]) / 1000.0

    # Avoid division by ~0
    d = d[d["Urban_edge_km"] > 0].copy()
    d["COD_kg_per_urban_edge_km_day"] = d["COD_kg_day"] / d["Urban_edge_km"]

    # Summarize by PD quantile
    out = (
        d.groupby("Urban_PD_quantile", as_index=False)
        .agg(
            N=("COD_kg_per_urban_edge_km_day", "size"),
            COD_kg_per_edge_km_day_mean=("COD_kg_per_urban_edge_km_day", "mean"),
            COD_kg_per_edge_km_day_median=("COD_kg_per_urban_edge_km_day", "median"),
            COD_kg_per_edge_km_day_p25=("COD_kg_per_urban_edge_km_day", lambda x: float(np.nanpercentile(x, 25))),
            COD_kg_per_edge_km_day_p75=("COD_kg_per_urban_edge_km_day", lambda x: float(np.nanpercentile(x, 75))),
        )
    )

    out_path = os.path.join(OUTPUT_DIR, "cod_load_per_urban_edge_km_by_pd_latest.csv")
    out.to_csv(out_path, index=False)
    print(f"Saved COD per-urban-edge diagnostic: {out_path}")


if __name__ == "__main__":
    main()
